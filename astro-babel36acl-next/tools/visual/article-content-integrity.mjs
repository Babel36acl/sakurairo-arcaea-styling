import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import matter from 'gray-matter';
import {fromHtml} from 'hast-util-from-html';
import {renderLegacyArticle} from '../../src/utils/legacy-article-renderer.ts';
import {normalizeMarkdownHeadingDepth} from '../../scripts/legacy-heading-normalization.mjs';
const original=matter(await fs.readFile('../astro-babel36acl/src/content/articles/legacy-798/index.md','utf8')).content;
const migrated=matter(await fs.readFile('src/content/posts/wp-798.md','utf8')).content;
const rendered=renderLegacyArticle(migrated);
const flatten=node=>[node,...(node.children||[]).flatMap(flatten)];
const text=node=>node.type==='text'?node.value:(node.children||[]).map(text).join('');
const source=flatten(fromHtml(original,{fragment:true}));
const candidate=flatten(fromHtml(rendered.html,{fragment:true}));
const code=nodes=>nodes.filter(n=>n.tagName==='pre').map(text);
assert.deepEqual(code(candidate),code(source),'Every original code/diagram block must retain its source');
const headings=nodes=>nodes.filter(n=>/^h[2-4]$/.test(n.tagName)).map(n=>({tag:n.tagName,text:text(n)}));
assert.deepEqual(headings(candidate),headings(source),'Heading hierarchy and text must survive migration');
const prose=nodes=>nodes.filter(n=>n.tagName==='p').map(n=>text(n).replace(/\s+/g,' ').trim());
assert.deepEqual(prose(candidate),prose(source),'Paragraph content must survive migration');
for(const sample of ['<pre><code>\n# comment\n## comment\n</code></pre>','```sh\n# comment\n```','~~~sh\n# comment\n~~~'])assert.equal(normalizeMarkdownHeadingDepth(sample),sample);
assert.equal(normalizeMarkdownHeadingDepth('# prose\n<pre>\n# shell\n</pre>\n# another'),'## prose\n<pre>\n# shell\n</pre>\n## another');
const result={pass:true,headings:rendered.headings.length,codeAndDiagramBlocks:code(candidate).length,paragraphs:prose(candidate).length,sourcePreserved:true,normalizationCases:4};
await fs.writeFile('reports/visual/phase3a/content-integrity.json',JSON.stringify(result,null,2));console.log(result);
